"""Namespaced errors shared by HTTP and background execution paths."""

from dataclasses import dataclass
from enum import StrEnum


class ErrorCode(StrEnum):
    AUTH_INVALID_KEY = "AUTH_INVALID_KEY"
    AUTH_REVOKED_KEY = "AUTH_REVOKED_KEY"
    AUTH_INSUFFICIENT_SCOPE = "AUTH_INSUFFICIENT_SCOPE"
    AUTH_ENVIRONMENT_MISMATCH = "AUTH_ENVIRONMENT_MISMATCH"
    REQ_INVALID = "REQ_INVALID"
    REQ_MISSING_SOURCE = "REQ_MISSING_SOURCE"
    REQ_MISSING_OUTPUT = "REQ_MISSING_OUTPUT"
    REQ_TOO_LARGE = "REQ_TOO_LARGE"
    REQ_IDEMPOTENCY_CONFLICT = "REQ_IDEMPOTENCY_CONFLICT"
    PAYLOAD_TOO_LARGE = "PAYLOAD_TOO_LARGE"
    SOURCE_TOO_LARGE = "SOURCE_TOO_LARGE"
    GENERATED_OUTPUT_TOO_LARGE = "GENERATED_OUTPUT_TOO_LARGE"
    UNSUPPORTED_SOURCE_TYPE = "UNSUPPORTED_SOURCE_TYPE"
    UNSUPPORTED_OUTPUT_TYPE = "UNSUPPORTED_OUTPUT_TYPE"
    INGESTION_LIMIT_EXCEEDED = "INGESTION_LIMIT_EXCEEDED"
    INGESTION_FAILED = "INGESTION_FAILED"
    EVALUATION_FAILED = "EVALUATION_FAILED"
    RESOURCE_CONFLICT = "RESOURCE_CONFLICT"
    RESOURCE_REFERENCE_INVALID = "RESOURCE_REFERENCE_INVALID"
    SYSTEM_NOT_FOUND = "SYSTEM_NOT_FOUND"
    SYSTEM_INACTIVE = "SYSTEM_INACTIVE"
    VERSION_NOT_FOUND = "VERSION_NOT_FOUND"
    RELEASE_POLICY_INACTIVE = "RELEASE_POLICY_INACTIVE"
    AI_TIMEOUT = "AI_TIMEOUT"
    AI_UNAUTHORIZED = "AI_UNAUTHORIZED"
    AI_RATE_LIMITED = "AI_RATE_LIMITED"
    AI_SERVER_ERROR = "AI_SERVER_ERROR"
    AI_INVALID_RESPONSE = "AI_INVALID_RESPONSE"
    NER_FAILED = "NER_FAILED"
    ALIGNMENT_UNCERTAIN = "ALIGNMENT_UNCERTAIN"
    SEMANTIC_EVALUATOR_FAILED = "SEMANTIC_EVALUATOR_FAILED"
    NORMALIZATION_FAILED = "NORMALIZATION_FAILED"
    COVERAGE_REDUCED = "COVERAGE_REDUCED"
    UNASSESSED_CASES_PRESENT = "UNASSESSED_CASES_PRESENT"
    DATABASE_UNAVAILABLE = "DATABASE_UNAVAILABLE"
    WORKER_FAILED = "WORKER_FAILED"
    BATTERY_DISABLED = "BATTERY_DISABLED"
    EVALUATOR_NOT_IMPLEMENTED = "EVALUATOR_NOT_IMPLEMENTED"
    EVALUATOR_INVALID_RESULT = "EVALUATOR_INVALID_RESULT"


@dataclass(slots=True)
class GatekeeperError(Exception):
    code: ErrorCode
    message: str
    retryable: bool = False
    http_status: int = 400
    resource_id: str | None = None

    def __str__(self) -> str:
        return self.message
